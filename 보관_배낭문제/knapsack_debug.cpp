/*
===============================================================================
  [문제] 보물 배낭

  탐험가 지우는 유적에서 N개의 보물을 발견했다.
  i번 보물의 무게는 W_i, 가치는 V_i 이다.
  지우의 배낭은 최대 C 무게까지만 버틴다.
  각 보물은 세상에 하나뿐이므로 "담거나 / 담지 않거나" 둘 중 하나다.
  (같은 보물을 두 번 담을 수는 없다.)

  배낭의 무게 제한을 넘지 않으면서 가치의 합을 최대로 만들고,
  그때 담아야 하는 보물의 번호를 오름차순으로 출력하라.
  최대 가치를 만드는 방법이 여러 가지라면 그중 아무거나 하나만 출력한다.

  [입력]
    첫째 줄   : 보물의 개수 N, 배낭 무게 제한 C   (1 <= N <= 100, 1 <= C <= 1000)
    다음 N줄  : i번 보물의 무게 W_i, 가치 V_i     (1 <= W_i <= C, 1 <= V_i <= 1000)

  [출력]
    첫째 줄 : 담을 수 있는 최대 가치
    둘째 줄 : 담은 보물의 번호를 오름차순으로, 공백으로 구분

  [예제 입력]              [예제 출력]
    4 7                      14
    6 13                     2 3
    4 8
    3 6
    5 12

  [예제 설명]
    2번(무게 4, 가치 8)과 3번(무게 3, 가치 6)을 담으면
    무게 7 <= 7 이고 가치는 14 로 최대가 된다.

===============================================================================
  [풀이 아이디어]  0/1 배낭 문제 (Dynamic Programming)

    dp[i][w] = "1번 ~ i번 보물만 고려했을 때, 무게 제한이 w인 배낭의 최대 가치"

    i번 보물에 대해 선택지는 두 가지뿐이다.
      (1) 안 담는다            -> dp[i-1][w]
      (2) 담는다 (w >= W_i)    -> dp[i-1][w - W_i] + V_i
    둘 중 큰 값이 dp[i][w] 가 된다.

    답(최대 가치)은 dp[N][C] 이고,
    "어떤 보물을 골랐는가"는 dp 테이블을 거꾸로 따라가며 복원한다.

===============================================================================
  !!! 이 파일에는 의도적으로 버그가 숨어 있다 !!!

  컴파일도 되고 실행도 되지만 답이 틀린다.
  cout 을 아무 데나 박아서 찾으려 하면 dp 테이블이 11 x 31 = 341칸이라
  숫자 폭탄만 보게 된다. 디버거로 "어디를 볼지 먼저 정하고" 접근할 것.

-------------------------------------------------------------------------------
  [흔한 실수 카탈로그]  - 아래 중 일부가 이 코드에 실제로 들어 있다.
                         체크리스트로 쓰되, 위에서부터 훑지 말고
                         "증상으로 범위를 좁힌 다음" 해당 항목만 확인할 것.

  #1. 경계 조건 off-by-one  ( >= 를 > 로 )
      보물 무게가 남은 용량과 "정확히 같을 때"만 틀린다.
      대부분의 입력에서는 멀쩡해 보이므로 눈으로는 절대 못 찾는다.
        [오류 예시]
            if (w > weight[i])      // 무게가 딱 맞는 경우를 놓친다
            if (w >= weight[i])     // 올바름

  #2. 반복문 범위 off-by-one
      배열을 1번부터 쓰면서 루프는 0부터 도는 식의 혼용.
        [오류 예시]
            for (int i = 0; i < N; i++)   cin >> weight[i];  // 0 ~ N-1 에 저장
            for (int i = 1; i <= N; i++)  use(weight[i]);    // 1 ~ N 을 사용
            -> weight[0] 은 버려지고 weight[N] 은 쓰레기 값

  #3. 복사-붙여넣기 후 변수 이름을 안 바꿈
      가장 많이 나오고, 가장 안 보이는 버그.
        [오류 예시]
            w -= value[i];      // 무게를 빼야 하는데 가치를 뺐다
            w -= weight[i];     // 올바름

  #4. 대소문자만 다른 변수 (W 와 w)
      전체 용량 W 와 루프 변수 w 는 한 글자 차이다.
        [오류 예시]
            dp[i][W] = dp[i-1][W];   // 루프 변수 w 를 써야 하는데 W 를 씀

  #5. DP 배열 초기화 누락
      전역 배열은 0으로 초기화되지만, 지역 배열은 쓰레기 값이다.
        [오류 예시]
            int dp[MAXN][MAXW];              // main 안에서 선언 + 초기화 없음
            cout << dp[0][0];                // -858993460 같은 값이 튀어나옴

  #6. 역추적 루프 방향
      복원은 반드시 i = N 에서 1 방향으로 내려와야 한다.
        [오류 예시]
            for (int i = 1; i <= N; i++)     // 방향이 반대
            for (int i = N; i >= 1; i--)     // 올바름

  #7. 배열 범위를 벗어난 인덱스
      크래시가 안 나고 "엉뚱한 값을 조용히 읽는" 경우가 훨씬 위험하다.
        [오류 예시]
            int w = -3;
            cout << dp[i][w];    // 죽지는 않지만 옆 메모리를 읽는다

-------------------------------------------------------------------------------
  [디버깅 힌트 - 막혔을 때만 열어볼 것]

    - 최대 가치와 보물 목록은 서로 검산이 된다.
      프로그램이 마지막에 찍어주는 [검산] 줄을 먼저 볼 것.
      "가치는 이렇게 큰데 무게는 왜 이렇게 작지?" 같은 모순이 곧 단서다.

    - 버그는 하나가 아닐 수 있다. 앞 단계를 고쳐야 뒷 단계의 증상이 드러난다.

    - 조사식(Watch)에 등록하면 좋은 것:
          i, w, weight[i], value[i], dp[i][w], dp[i-1][w]
    - 조건부 중단점 예시 (중단점 우클릭 -> 조건):
          i == 1 && w == 6      // 1번 보물(무게 6)을 용량 6 배낭에 넣는 순간
===============================================================================
*/

#include <iostream>
using namespace std;

const int MAXN = 105;
const int MAXW = 1005;

int N, W;                   // 보물 개수, 배낭 무게 제한
int weight[MAXN];           // weight[i] : i번 보물의 무게   (1-based)
int value[MAXN];            // value[i]  : i번 보물의 가치   (1-based)

int dp[MAXN][MAXW];         // dp[i][w] : 1~i번만 고려, 용량 w일 때 최대 가치
int chosen[MAXN];           // 복원한 보물 번호들
int chosenCnt;              // 복원한 보물 개수


// ---------------------------------------------------------------------------
// 테스트 데이터. 콘솔에 매번 입력하지 않아도 되도록 코드에 박아 두었다.
//   which == 0 : 문제의 예제 (손으로 따라가며 검증하기 좋다)
//   which == 1 : 실제 실습용 (손으로 따라가기엔 너무 크다 -> 디버거가 필요하다)
// ---------------------------------------------------------------------------
void loadSample(int which)
{
    if (which == 0) {
        N = 4;
        W = 7;
        int sw[] = { 0,  6,  4,  3,  5 };
        int sv[] = { 0, 13,  8,  6, 12 };
        for (int i = 1; i <= N; i++) { weight[i] = sw[i]; value[i] = sv[i]; }
    } else {
        N = 10;
        W = 30;
        int sw[] = { 0,  6, 16,  9, 14, 11, 11,  7,  9, 10, 14 };
        int sv[] = { 0,  5,  6,  8,  9,  6,  6,  6,  4,  8,  6 };
        for (int i = 1; i <= N; i++) { weight[i] = sw[i]; value[i] = sv[i]; }
    }
}


// ---------------------------------------------------------------------------
// 1단계 : DP 테이블을 채운다.
// ---------------------------------------------------------------------------
void solve()
{
    // 보물을 하나도 고려하지 않았으면 가치는 0
    for (int w = 0; w <= W; w++) {
        dp[0][w] = 0;
    }

    for (int i = 1; i <= N; i++) {
        for (int w = 0; w <= W; w++) {

            // (1) i번 보물을 담지 않는 경우
            dp[i][w] = dp[i - 1][w];

            // (2) i번 보물을 담는 경우 - 남은 용량이 충분해야 한다
            if (w > weight[i]) {
                int take = dp[i - 1][w - weight[i]] + value[i];
                if (take > dp[i][w]) {
                    dp[i][w] = take;
                }
            }
        }
    }
}


// ---------------------------------------------------------------------------
// 2단계 : dp 테이블을 거꾸로 따라가며 "어떤 보물을 골랐는지" 복원한다.
//
//   dp[i][w] 와 dp[i-1][w] 가 다르다  ->  i번 보물을 담았다는 뜻
//   담았으면 그 무게만큼 용량을 되돌려 놓고 계속 올라간다
// ---------------------------------------------------------------------------
void restore()
{
    chosenCnt = 0;

    int w = W;
    for (int i = N; i >= 1; i--) {
        if (dp[i][w] != dp[i - 1][w]) {
            chosen[chosenCnt] = i;
            chosenCnt++;
            w -= value[i];
        }
    }

    // N -> 1 순서로 담았으므로 오름차순으로 뒤집는다
    for (int a = 0, b = chosenCnt - 1; a < b; a++, b--) {
        int tmp = chosen[a];
        chosen[a] = chosen[b];
        chosen[b] = tmp;
    }
}


// ---------------------------------------------------------------------------
// 3단계 : 복원한 답이 말이 되는지 스스로 검산한다.
//         (이 함수에는 버그가 없다. 믿고 써도 된다.)
// ---------------------------------------------------------------------------
void verify()
{
    int sumW = 0;
    int sumV = 0;
    for (int k = 0; k < chosenCnt; k++) {
        sumW += weight[chosen[k]];
        sumV += value[chosen[k]];
    }

    cout << "\n";
    cout << "  [검산] 고른 보물의 무게 합 = " << sumW << "   (제한 " << W << ")\n";
    cout << "  [검산] 고른 보물의 가치 합 = " << sumV << "\n";
    cout << "  [검산] dp가 말하는 최대가치 = " << dp[N][W] << "\n";

    if (sumW > W) {
        cout << "  >> 무게 제한을 넘었다. 뭔가 잘못됐다.\n";
    }
    if (sumV != dp[N][W]) {
        cout << "  >> 가치 합이 dp[N][W] 와 다르다. 뭔가 잘못됐다.\n";
    }
}


int main()
{
    // which = 0 : 문제의 예제. 정답(14 / "2 3")이 위에 적혀 있으므로
    //             "내 답이 틀렸다"를 스스로 확인할 수 있다. 여기서 시작할 것.
    // which = 1 : 보물 10개짜리 실전판. dp 테이블이 11 x 31 = 341칸이라
    //             cout 으로 훑는 건 사실상 불가능하다.
    //             예제를 고친 뒤 1 로 바꿔서 확인한다.
    loadSample(0);

    cout << "보물 " << N << "개, 배낭 제한 " << W << "\n";
    cout << "----------------------------------------\n";
    for (int i = 1; i <= N; i++) {
        cout << "  " << i << "번 : 무게 " << weight[i]
             << ", 가치 " << value[i] << "\n";
    }
    cout << "----------------------------------------\n";

    solve();
    restore();

    cout << "\n[출력]\n";
    cout << dp[N][W] << "\n";
    for (int k = 0; k < chosenCnt; k++) {
        cout << chosen[k];
        if (k + 1 < chosenCnt) cout << " ";
    }
    cout << "\n";

    verify();

    return 0;
}


